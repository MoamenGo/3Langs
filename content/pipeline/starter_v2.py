"""Build the phase 2 starter packs for all three languages.

    python content/pipeline/starter_v2.py

Writes:
  app/assets/content/de/a0.json, a1.json   (A1 regenerated by starter_a1.py)
  app/assets/content/nl/a0.json, a1.json
  app/assets/content/es/a0.json, a1.json
  app/assets/content/contrast.json

The hand-written data lives in content/data/starter/. German A1 comes from
starter_a1.py (then to_v2.py); this script adds Arabic and concept ids to it.
Dutch and Spanish A1 reuse the German unit and lesson layout, so the three
courses stay in step unit by unit.
"""
