def _norm(text: str) -> str:
    return " " + re.sub(r"[^\wäöüßáéíóúñüàèëïç' ]+", " ", text.lower()).replace("  ", " ") + " "


def _forms(lang: str, lemma: str, plural: str | None, pos: str) -> set[str]:
    out = {lemma.lower()}
    if plural:
        out.add(plural.lower())
    out.update(FORMS.get(lang, {}).get(lemma.lower(), []))
    if lang == "es" and pos == "adjective" and lemma.endswith("o"):
        stem = lemma[:-1]
        out.update({stem + "a", stem + "os", stem + "as"})
    if lang == "es" and pos == "adjective" and lemma.endswith("e"):
        out.add(lemma + "s")
    return out


def uses(text: str, forms: set[str]) -> bool:
    t = re.sub(r"\s+", " ", _norm(text))
    return any(re.sub(r"\s+", " ", _norm(f)) in t for f in forms)


def link_sentences(lang: str, vocab: list[dict], sentences: list[dict], limit: int = 3) -> None:
    for v in vocab:
        forms = _forms(lang, v["lemma"], v.get("plural"), v["pos"])
        v["sentenceIds"] = [s["id"] for s in sentences if uses(s["text"], forms)][:limit]


def vocab_entry(lang: str, level: str, lemma, article, plural, pos, en, ar, concept, taken: set) -> dict:
    base = f"{lang}.{level.lower()}.vocab.{slug(lemma)}"
    vid, n = base, 2
    while vid in taken:
        vid, n = f"{base}_{n}", n + 1
    taken.add(vid)
    return {
        "id": vid, "lemma": lemma, "article": article, "plural": plural, "pos": pos,
        "level": level, "freqRank": None, "translations": {"ar": ar, "en": en},
        "conceptId": f"c.{level.lower()}.{concept}", "sentenceIds": [],
        "source": SRC, "license": LIC,
    }


def grammar_entry(lang: str, level: str, key: str, g: dict, sent_prefix: str) -> dict:
    return {
        "id": f"{lang}.{level.lower()}.gram.{key}", "level": level,
        "title": g["title"], "explanation": g["explanation"], "table": g["table"],
        "exampleSentenceIds": [f"{sent_prefix}{k}" for k in g["examples"]],
        "exercises": [{"type": "fill_blank", "prompt": p, "answer": a, "base": b}
                      for p, a, b in g["exercises"]],
        "source": SRC, "license": LIC,
    }


def lang_names(lang: str) -> dict:
    en, ar = a1_shared.LANG_NAME[lang]
    return {"Len": en, "Lar": ar}


# ---------------------------------------------------------------- German A1


def patch_de_a1() -> dict:
    path = OUT / "de" / "a1.json"
    pack = json.loads(path.read_text(encoding="utf-8"))
    pack["contentVersion"] = VERSION
    for v in pack["vocab"]:
        v["conceptId"] = "c.a1." + a1_shared.CONCEPTS[v["id"].split(".")[-1]]
    for s in pack["sentences"]:
        s["translations"]["ar"] = a1_shared.SENT_AR[s["id"].split(".")[-1]]
    for g in pack["grammar"]:
        title, expl = a1_shared.DE_GRAMMAR_AR[g["id"]]
        g["title"]["ar"], g["explanation"]["ar"] = title, expl
    for t in pack["texts"]:
        t.setdefault("translation", {"en": ""})["ar"] = a1_shared.DE_TEXT_AR[t["id"]]
    prompts = {k: (en, ar) for k, _, en, ar in a1_shared.WRITING}
    for w in pack["writingPrompts"]:
        en, ar = prompts[w["id"].split(".")[-1]]
        w["prompt"]["ar"] = ar.format(**lang_names("de"))
    path.write_text(json.dumps(pack, ensure_ascii=False, indent=1), encoding="utf-8")
    return pack


# ------------------------------------------------------- Dutch/Spanish A1


def build_a1(lang: str, de: dict) -> dict:
    data = A1_DATA[lang]
    p = f"{lang}.a1."
    de_sent = list(starter_a1.SENTENCES) + [s for u in starter_a1_units.UNITS for s in u["sentences"]]
    col = {"nl": 3, "es": 4}[lang]
    over = getattr(data, "SENT_OVERRIDES", {})
    sentences = [{
        "id": f"{p}sent.{row[0]}", "text": over.get(row[0], row[col]),
        "translations": {"ar": a1_shared.SENT_AR[row[0]], "en": row[2]},
        "source": SRC, "license": LIC, "needsReview": False,
    } for row in de_sent]

    taken: set[str] = set()
    vocab, by_de = [], {}
    de_vocab = {v["id"].split(".")[-1]: v for v in de["vocab"]}
    for de_slug, dv in de_vocab.items():
        lemma, article, plural, pos, en, ar = data.VOCAB[de_slug]
        e = vocab_entry(lang, "A1", lemma, article, plural, pos,
                        en or dv["translations"]["en"], ar or dv["translations"]["ar"],
                        a1_shared.CONCEPTS[de_slug], taken)
        vocab.append(e)
        by_de[de_slug] = e["id"]
    link_sentences(lang, vocab, sentences)

    grammar = [grammar_entry(lang, "A1", g["slug"], g, f"{p}sent.") for g in data.GRAMMAR]
    gram_by_unit = {g["unit"]: f"{p}gram.{g['slug']}" for g in data.GRAMMAR}
    names = lang_names(lang)
    texts = [{
        "id": f"{p}text.{t['slug']}", "level": "A1", "kind": "reading", "title": t["title"],
        "body": t["body"], "translation": {"ar": t["ar"], "en": t["en"]},
        "glossary": [by_de[g] for g in t["glossary"]],
        "questions": [{"question": q, "options": o, "answer": a} for q, o, a in t["questions"]],
        "source": SRC, "license": LIC,
    } for t in data.TEXTS]
    text_by_unit = {t["unit"]: f"{p}text.{t['slug']}" for t in data.TEXTS}

    units, lessons = [], []
    for du in de["units"]:
        key = du["id"].split(".")[-1]
        u = copy.deepcopy(du)
        u["id"] = f"{p}{key}"
        u["grammarIds"] = [gram_by_unit[key]]
        u["lessonIds"] = [lid.replace("de.a1.", p) for lid in du["lessonIds"]]
        units.append(u)
    for dl in de["lessons"]:
        l = copy.deepcopy(dl)
        l["id"] = dl["id"].replace("de.a1.", p)
        l["unitId"] = dl["unitId"].replace("de.a1.", p)
        short = ".".join(l["id"].split(".")[-2:])
        if short in data.LESSON_TITLES:
            l["title"] = data.LESSON_TITLES[short]
        unit_key = l["unitId"].split(".")[-1]
        if l["type"] in ("vocab", "review"):
            l["items"] = [by_de[i.split(".")[-1]] for i in dl["items"]]
        elif l["type"] == "listening":
            l["items"] = [i.replace("de.a1.", p) for i in dl["items"]]
        if l["type"] == "grammar":
            l["grammarId"] = gram_by_unit[unit_key]
        if l["type"] == "reading":
            l["textId"] = text_by_unit[unit_key]
        lessons.append(l)

    writing = [{
        "id": f"{p}write.{k}", "level": "A1",
        "prompt": {"ar": ar.format(**names), "en": en.format(**names)}, "minWords": n,
    } for k, n, en, ar in a1_shared.WRITING]

    return {
        "schemaVersion": 2, "lang": lang, "contentVersion": VERSION,
        "level": de["level"], "units": units, "lessons": lessons, "vocab": vocab,
        "sentences": sentences, "grammar": grammar, "texts": texts,
        "writingPrompts": writing,
        "credits": [{"name": "3Lang original content", "license": LIC}],
    }


# ------------------------------------------------------------------- A0


def build_a0(lang: str) -> dict:
    p = f"{lang}.a0."
    col = {"de": 4, "nl": 5, "es": 6}[lang]
    names = lang_names(lang)
    sentences = [{
        "id": f"{p}sent.{row[0]}", "text": row[col],
        "translations": {"ar": row[3].format(**names), "en": row[2].format(**names)},
        "source": SRC, "license": LIC, "needsReview": False,
    } for row in a0.SENTENCES]

    taken: set[str] = set()
    vocab, by_concept, by_group = [], {}, {}
    for group, rows in a0.VOCAB.items():
        by_group[group] = []
        for concept, en, ar, forms in rows:
            lemma, article, plural, pos = forms[lang]
            e = vocab_entry(lang, "A0", lemma, article, plural, pos, en, ar, concept, taken)
            vocab.append(e)
            by_concept[concept] = e["id"]
            by_group[group].append(e["id"])
    link_sentences(lang, vocab, sentences)

    lg = a0_lang.GRAMMAR[lang]
    grammar = [grammar_entry(lang, "A0", k, g, f"{p}sent.") for k, g in lg.items()]
    t = a0_lang.TEXTS[lang]
    texts = [{
        "id": f"{p}text.hotel", "level": "A0", "kind": "reading", "title": t["title"],
        "body": t["body"],
        "translation": {"ar": a0_lang.TEXT_AR.format(**names), "en": a0_lang.TEXT_EN.format(**names)},
        "glossary": [by_concept[c] for c in t["glossary"]],
        "questions": [{"question": q, "options": o, "answer": a} for q, o, a in t["questions"]],
        "source": SRC, "license": LIC,
    }]

    units, lessons = [], []
    for order, (key, meta) in enumerate(a0.UNITS.items(), start=1):
        uid = f"{p}{key}"
        unit_vocab = [i for g, ids in by_group.items() if g.startswith(key) for i in ids]
        lesson_ids, grammar_ids = [], []
        for n, (ltype, ref, title) in enumerate(a0.LESSONS[key], start=1):
            lid = f"{uid}.l{n:02d}"
            lesson = {"id": lid, "unitId": uid, "order": n, "type": ltype, "title": title, "items": []}
            if ltype == "vocab":
                lesson["items"] = by_group[ref]
            elif ltype == "review":
                lesson["items"] = unit_vocab
            elif ltype == "listening":
                lesson["items"] = [f"{p}sent.{k}" for k in a0.LISTENING[ref]]
            elif ltype == "grammar":
                lesson["grammarId"] = f"{p}gram.{ref}"
                grammar_ids.append(lesson["grammarId"])
            elif ltype == "reading":
                lesson["textId"] = f"{p}text.{ref}"
            lessons.append(lesson)
            lesson_ids.append(lid)
        units.append({
            "id": uid, "level": "A0", "order": order, "theme": meta["theme"],
            "goals": meta["goals"], "grammarIds": grammar_ids, "lessonIds": lesson_ids,
            "sharedUnitId": f"u.a0.{order:02d}",
        })

    k, n, en, ar = a0_lang.WRITING
    writing = [{"id": f"{p}write.{k}", "level": "A0",
                "prompt": {"ar": ar.format(**names), "en": en.format(**names)}, "minWords": n}]

    return {
        "schemaVersion": 2, "lang": lang, "contentVersion": VERSION,
        "level": {"id": "A0", **a0.LEVEL}, "units": units, "lessons": lessons,
        "vocab": vocab, "sentences": sentences, "grammar": grammar, "texts": texts,
        "writingPrompts": writing,
        "credits": [{"name": "3Lang original content", "license": LIC}],
    }


# ------------------------------------------------------------- contrast

NAME_AR = {"de": "ألماني", "nl": "هولندي", "es": "إسباني", "en": "إنجليزي"}
NAME_EN = {"de": "German", "nl": "Dutch", "es": "Spanish", "en": "English"}
GENDER = {"der": "m", "die": "f", "das": "n", "el": "m", "la": "f", "de": "c", "het": "n"}
GENDER_EN = {"m": "masculine", "f": "feminine", "n": "neuter", "c": "common (de)"}
GENDER_AR = {"m": "مذكر", "f": "مؤنث", "n": "محايد", "c": "de (مشترك)"}


def _mismatch(de: str, other: str, lang: str) -> bool:
    """True when the other language's article is not the one a German learner would guess."""
    if lang == "nl":  # German das usually goes with Dutch het, der/die with de
        return (de == "das") != (other == "het")
    if de == "das":  # Spanish has no neuter, so there is nothing to guess
        return False
    return GENDER[de] != GENDER[other]


def build_contrast(packs: dict[tuple[str, str], dict]) -> dict:
    entries = []
    for key, kind, level, forms, en, ar in contrast.HAND:
        entries.append({"id": f"x.{key}", "kind": kind, "level": level, "forms": forms,
                        "note": {"ar": ar, "en": en}})

    concepts: dict[str, dict[str, dict]] = {}
    for (lang, _), pack in packs.items():
        for v in pack["vocab"]:
            concepts.setdefault(v["conceptId"], {})[lang] = v
    hand_de = {f.get("de") for _, _, _, f, _, _ in contrast.HAND}
    for cid, words in concepts.items():
        if len(words) < 3:
            continue
        level = next(iter(words.values()))["level"]
        disp = {l: (f"{w['article']} {w['lemma']}" if w["article"] else w["lemma"]) for l, w in words.items()}
        # Gender mismatches between German and each of the other two.
        de = words["de"]
        for other in ("nl", "es"):
            o = words[other]
            if de["article"] and o["article"] and _mismatch(de["article"], o["article"], other):
                g1, g2 = GENDER[de["article"]], GENDER[o["article"]]
                entries.append({
                    "id": f"x.gender_{other}_{cid.split('.')[-1]}", "kind": "gender_mismatch",
                    "conceptId": cid, "level": level, "forms": {"de": disp["de"], other: disp[other]},
                    "note": {
                        "en": f"Different gender: German {disp['de']} ({GENDER_EN[g1]}), {NAME_EN[other]} {disp[other]} ({GENDER_EN[g2]}).",
                        "ar": f"الجنس مختلف: ألماني {disp['de']} ({GENDER_AR[g1]})، {NAME_AR[other]} {disp[other]} ({GENDER_AR[g2]}).",
                    },
                })
        # Near cognates: the German and Dutch (or Spanish) words look alike.
        lem = {l: w["lemma"].lower() for l, w in words.items()}
        pairs = [(a, b) for a, b in (("de", "nl"), ("de", "es"), ("nl", "es"))
                 if difflib.SequenceMatcher(None, lem[a], lem[b]).ratio() >= 0.7]
        if pairs and disp["de"] not in hand_de and words["de"]["pos"] in ("noun", "verb", "adjective", "numeral"):
            same = sorted({l for pr in pairs for l in pr}, key=LANGS.index)
            entries.append({
                "id": f"x.cognate_{cid.split('.')[-1]}", "kind": "near_cognate",
                "conceptId": cid, "level": level, "forms": {l: disp[l] for l in LANGS},
                "note": {
                    "en": "Looks alike in " + " and ".join(NAME_EN[l] for l in same)
                          + f": learn them together. ({words['de']['translations']['en']})",
                    "ar": "شبه بعض في ال" + " وال".join(NAME_AR[l] for l in same)
                          + f": احفظهم مع بعض. ({words['de']['translations']['ar']})",
                },
            })
    return {"schemaVersion": 1, "entries": entries}


# ------------------------------------------------------------------- main


def main() -> None:
    starter_a1.main()  # German A1 as v2
    packs: dict[tuple[str, str], dict] = {("de", "A1"): patch_de_a1()}
    for lang in ("nl", "es"):
        packs[(lang, "A1")] = build_a1(lang, packs[("de", "A1")])
    for lang in LANGS:
        packs[(lang, "A0")] = build_a0(lang)
    for (lang, level), pack in packs.items():
        out = OUT / lang / f"{level.lower()}.json"
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(json.dumps(pack, ensure_ascii=False, indent=1), encoding="utf-8")
        print(f"wrote {out.relative_to(ROOT)}: {len(pack['vocab'])} words, "
              f"{len(pack['sentences'])} sentences, {len(pack['lessons'])} lessons")
    c = build_contrast(packs)
    (OUT / "contrast.json").write_text(json.dumps(c, ensure_ascii=False, indent=1), encoding="utf-8")
    kinds = {}
    for e in c["entries"]:
        kinds[e["kind"]] = kinds.get(e["kind"], 0) + 1
    print(f"wrote app/assets/content/contrast.json: {kinds}")


if __name__ == "__main__":
    main()
